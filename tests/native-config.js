import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../../deepseek-harness-latest', import.meta.url));
const source = await readFile(resolve(root, 'tsconfig.base.json'), 'utf8');
const original = JSON.parse(source.replace(/^\s*\/\/.*$/gm, ''));
const paths = Object.fromEntries(Object.entries(original.compilerOptions.paths).map(([name, values]) => [name, values.map(value => resolve(root, value))]));
for (const name of ['vanilla', 'middleware', 'shallow']) paths[`zustand/${name}`] = [resolve(import.meta.dirname, `../node_modules/zustand/${name}.js`)];
paths.immer = [resolve(import.meta.dirname, '../node_modules/immer/dist/immer.mjs')];
await writeFile(new URL('./.native-tsconfig.json', import.meta.url), JSON.stringify({ compilerOptions: { paths } }, null, 2) + '\n');
